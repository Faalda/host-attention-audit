def donor_permutation(n=1000):
    """Rejection is only for fixed points, never captions or measured outcomes."""
    if n < 2:
        raise ValueError("Derangement requires at least two images")
    rng = np.random.default_rng(DONOR_SEED)
    attempts = 0
    while True:
        attempts += 1
        perm = rng.permutation(n)
        if np.all(perm != np.arange(n)):
            return perm.tolist(), attempts


def donor_memory(projected_donors, recipient_mask, mu):
    """Donor vector at spatial position p goes to the SAME recipient position p."""
    if (projected_donors.ndim != 3 or recipient_mask.dtype != torch.bool
            or recipient_mask.shape != projected_donors.shape[:2]
            or mu.shape != projected_donors.shape[2:]):
        raise ValueError("Feature/mask/mean shape mismatch")
    if not torch.isfinite(projected_donors).all() or not torch.isfinite(mu).all():
        raise ValueError("Nonfinite donor features or training mean")
    return torch.where(recipient_mask[..., None], projected_donors, mu[None, None])


def caption_prefix(tok, captions, device="cpu"):
    # BOS + generated words, no appended EOS. The last valid input predicts EOS
    # for stopped captions; max-length generations have at most 39 input states.
    return torch.tensor([tok.enc(c, max_len=39, bos=True, eos=False) for c in captions], device=device)


@contextmanager
def capture_attention(dec):
    """Call native layers with ret_attn=True; never replace the class or QK math."""
    captured = [None] * len(dec.layers)
    originals = [(layer.forward, "forward" in layer.__dict__, layer.__dict__.get("forward"))
                 for layer in dec.layers]

    def wrapper(original, index):
        def forward(x, mem, attn_plan, tgt_mask=None, tgt_pad=None, ret_attn=False):
            hidden, weights = original(x, mem, attn_plan, tgt_mask=tgt_mask, tgt_pad=tgt_pad, ret_attn=True)
            captured[index] = weights.detach()
            return (hidden, weights) if ret_attn else hidden
        return forward

    try:
        for i, layer in enumerate(dec.layers):
            layer.forward = wrapper(originals[i][0], i)
        yield captured
    finally:
        for layer, (_, had_override, value) in zip(dec.layers, originals):
            if had_override:
                layer.forward = value
            else:
                delattr(layer, "forward")


@torch.no_grad()
def anchor_attention(dec, memory, plans, mask, prefix):
    from inversion.run_rev_inversion_protocol import dec_forward
    valid = prefix != 0
    if not valid.any(1).all():
        raise ValueError("Empty autogenerated prefix")
    output = {}
    for name in ("fault", "repair"):
        native = dec_forward(dec, memory, prefix, plans[name])
        with capture_attention(dec) as weights:
            measured = dec_forward(dec, memory, prefix, plans[name])
        if not torch.isfinite(native).all() or not torch.isfinite(measured).all():
            raise ValueError("Nonfinite attention-probe logits")
        torch.testing.assert_close(native, measured, rtol=0, atol=0)
        layers = []
        for w in weights:
            if w is None or not torch.isfinite(w).all():
                raise ValueError("Missing/nonfinite native attention")
            torch.testing.assert_close(w.sum(-1), torch.ones_like(w[..., 0]), rtol=1e-5, atol=1e-6)
            mass = (w * mask[:, None]).sum(-1)
            layers.append([mass[i][valid[i]].cpu().tolist() for i in range(len(prefix))])
        output[name] = layers
    return output


def distribution(values):
    arr = np.asarray(values, dtype=float)
    if not arr.size or not np.isfinite(arr).all():
        raise ValueError("Empty/nonfinite distribution")
    return dict(n=int(arr.size), mean=float(arr.mean()), std=float(arr.std()),
                quantiles=dict(zip(("min", "p05", "p25", "median", "p75", "p95", "max"),
                                   np.quantile(arr, [0, .05, .25, .5, .75, .95, 1]).tolist())))


def score_outputs(captions, refs, perm):
    if len(refs) != len(perm) or any(len(rr) != 5 for rr in refs):
        raise ValueError("All five references and all recipients required")
    return {against: {name: [max(score(cap, ref) for ref in refs[perm[i] if against == "donor_refs" else i])
                             for i, cap in enumerate(cc)] for name, cc in captions.items()}
            for against in ("own_refs", "donor_refs")}


def aggregate(results):
    comparisons = {}
    arrays = {name: np.mean([r["scores"]["own_refs"][name] for r in results], axis=0)
              for name in results[0]["captions"]}
    contrasts = {
        "repair_own_minus_donor": (arrays["own_repair"], arrays["donor_repair"]),
        "fault_own_minus_donor": (arrays["own_fault"], arrays["donor_fault"]),
        "own_repair_minus_fault": (arrays["own_repair"], arrays["own_fault"]),
        "donor_repair_minus_fault": (arrays["donor_repair"], arrays["donor_fault"]),
        "interaction": (arrays["own_repair"] - arrays["own_fault"],
                        arrays["donor_repair"] - arrays["donor_fault"]),
        "null_repair_minus_fault": (arrays["null_repair"], arrays["null_fault"]),
    }
    for name, (a, b) in contrasts.items():
        comparisons[name] = paired(a, b, resamples=10000, seed=0)
    donor_scores = {name: np.mean([r["scores"]["donor_refs"][name] for r in results], axis=0)
                    for name in arrays}
    corroboration = {name: paired(donor_scores["donor_" + name], arrays["donor_" + name])
                     for name in ("fault", "repair")}
    attention = {}
    for condition in ("fault", "repair"):
        attention[condition] = []
        for layer in range(3):
            seed_image_means = np.array([r["attention"][condition][layer]["image_mean"] for r in results])
            attention[condition].append(dict(layer=layer,
                pooled_seed_average_images=distribution(seed_image_means.mean(0)),
                all_seed_image_pairs=distribution(seed_image_means.flatten()),
                per_seed={r["seed"]: distribution(seed_image_means[i]) for i, r in enumerate(results)},
                prior_anchor_mass=float(np.mean([r["prior_anchor_mass"][condition] for r in results]))))
    invariance = all(r["null"]["identical_captions_across_masks_and_plans"] and
                     r["null"]["shared_prefix_logits_within_1e_minus4_tolerance"] for r in results)
    positive = comparisons["interaction"]["ci95"][0] > 0 and comparisons["repair_own_minus_donor"]["ci95"][0] > 0
    return dict(comparisons=comparisons, donor_reference_corroboration=corroboration,
                own_reference_means={k: float(v.mean()) for k, v in arrays.items()},
                donor_reference_means={k: float(v.mean()) for k, v in donor_scores.items()},
                attention=attention, interaction_and_repair_difference_positive=positive,
                all_mean_null_invariance_passed=invariance,
                confirms_visual_basis_in_this_control=bool(positive and invariance),
                uncertainty="10000 paired recipient-image bootstrap draws, seed0, after averaging three fixed seeds; fixed donor permutation",
                interpretation="Post-lock diagnostic, not preregistered; not an ordinary photographic corruption or a universal visual-headroom estimator. Native QK remains active; fault anchors are not literally unavailable.")


def check_gpu0():
    snapshot = gpu_snapshot()
    row = next(row.split(", ") for row in snapshot["gpus"] if row.split(", ")[0] == "0")
    if float(row[3]) < 24000:
        raise RuntimeError("GPU0 has less than 24000 MiB free; refusing allocation")
    return row[1], snapshot


@torch.no_grad()
def run_seed(seed):
    folder = OUT / f"seed{seed}"
    folder.mkdir(exist_ok=False)
    uuid, snapshot = check_gpu0()
    if os.environ.get("CUDA_VISIBLE_DEVICES") != uuid:
        raise RuntimeError("Worker must expose only physical GPU0 by UUID")
    torch.cuda.set_per_process_memory_fraction(.35, 0)
    assert torch.cuda.device_count() == 1
    torch.set_num_threads(4)
    torch.manual_seed(0)
    torch.use_deterministic_algorithms(True)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    atomic_json(folder / "gpu_before.json", dict(**snapshot, own_pid=os.getpid(), gpu_uuid=uuid, memory_fraction=.35))
    config = read_json(OUT / "local_plan.json")
    perm = config["donor_permutation"]
    assert config["k"] == 16 and perm == donor_permutation()[0]
    tok, models = load_models(MODELS / f"seed{seed}", "cuda")
    before = model_digest(models)
    prior_folder = ORIGINAL / f"seed{seed}"
    assert before == read_json(prior_folder / "test/complete.json")["state_sha256_after"]
    original = read_json(prior_folder / "test/forward.json")["captions"]
    own = torch.load(prior_folder / "test/fault_features.pt", map_location="cpu", weights_only=True, mmap=True)
    masks = torch.load(prior_folder / "test/anchor_mask.pt", map_location="cpu", weights_only=True)
    mu = torch.load(prior_folder / "train_mean.pt", map_location="cpu", weights_only=True).cuda()
    features = torch.load(FEATURES, map_location="cpu", weights_only=True, mmap=True)
    assert own.shape == (1000, 256, 256) and masks.shape == (1000, 256) and (masks.sum(1) == 16).all()
    assert all(not m.training for model in models.values() for m in model.modules())
    captions = {name: [] for name in ("own_fault", "own_repair", "donor_fault", "donor_repair", "null_fault", "null_repair")}
    attention = {name: [[] for _ in range(3)] for name in ("fault", "repair")}
    prefixes, null_prefixes, null_deltas, null_all_deltas = [], [], [], []
    donor_tensors = []
    prior_mass = {name: [] for name in ("fault", "repair")}
    from inversion.run_rev_inversion_protocol import dec_forward
    dec = models["guided"]
    for start in range(0, 1000, BATCH):
        stop = min(start + BATCH, 1000)
        mask = masks[start:stop].cuda()
        plans = routing_plans(mask)
        xown = own[start:stop].cuda()
        projected = models["proj"](features[[14000 + p for p in perm[start:stop]]].cuda())
        xdonor = donor_memory(projected, mask, mu)
        assert torch.equal(xdonor[mask], projected[mask])
        assert torch.equal(xdonor[~mask], mu.expand_as(xdonor)[~mask])
        assert torch.equal(xown[~mask], mu.expand_as(xown)[~mask])
        donor_tensors.append(xdonor.cpu())
        xnull = mu[None, None].expand_as(xown).contiguous()
        batch_captions = {}
        for memory_name, memory in (("own", xown), ("donor", xdonor), ("null", xnull)):
            for plan_name in ("fault", "repair"):
                name = memory_name + "_" + plan_name
                cc = generate(tok, dec, memory, plans[plan_name])
                captions[name] += cc
                batch_captions[name] = cc
        for name in ("fault", "repair"):
            if batch_captions["own_" + name] != original[name][start:stop]:
                raise RuntimeError(f"Original own-{name} replay mismatch; no valid paired diagnostic")
            prior_mass[name] += (plans[name][:, 0] * mask).sum(-1).cpu().tolist()
        prefix = caption_prefix(tok, batch_captions["own_fault"], "cuda")
        prefixes += prefix.cpu().tolist()
        measured = anchor_attention(dec, xown, plans, mask, prefix)
        for condition in attention:
            for layer in range(3):
                attention[condition][layer] += measured[condition][layer]
        null_prefix = prefix
        null_prefixes += null_prefix.cpu().tolist()
        a = dec_forward(dec, xnull, null_prefix, plans["fault"])
        b = dec_forward(dec, xnull, null_prefix, plans["repair"])
        if not torch.isfinite(a).all() or not torch.isfinite(b).all():
            raise ValueError("Nonfinite all-mean null logits")
        diff = (a - b).abs().max(-1).values
        null_deltas += [diff[i][null_prefix[i] != 0].max().item() for i in range(len(prefix))]
        null_all_deltas += diff.max(-1).values.cpu().tolist()
        print(f"seed{seed}: {stop}/1000; null valid-prefix max logit difference {max(null_deltas):.8g}", flush=True)
    with (folder / "donor_features.pt").open("xb") as stream:
        torch.save(torch.cat(donor_tensors), stream)
    attn_summary = {name: [dict(per_valid_prefix_position=values,
                              image_mean=[float(np.mean(v)) for v in values],
                              image_distribution=distribution([np.mean(v) for v in values]),
                              token_weighted_mean=float(np.mean([v for row in values for v in row])))
                           for values in layers] for name, layers in attention.items()}
    refs = [r["refs"] for r in validate_source(read_json(SOURCE))]
    null = dict(fault_unique_captions=sorted(set(captions["null_fault"])),
                repair_unique_captions=sorted(set(captions["null_repair"])),
                paired_caption_mismatches=sum(a != b for a, b in zip(captions["null_fault"], captions["null_repair"])),
                identical_captions_across_masks_and_plans=len(set(captions["null_fault"] + captions["null_repair"])) == 1,
                shared_fault_prefix_tokens=null_prefixes, per_image_max_abs_valid_prefix_logits=null_deltas,
                max_abs_valid_prefix_logits=max(null_deltas), max_abs_all_prefix_logits=max(null_all_deltas),
                prefix_source="same autogenerated own-fault baseline prefix used for attention; no references",
                tolerance=1e-4, shared_prefix_logits_within_1e_minus4_tolerance=max(null_deltas) <= 1e-4,
                measured_without_forcing_equality=True)
    after = model_digest(models)
    assert before == after
    assert all(not p.requires_grad and p.grad is None for m in models.values() for p in m.parameters())
    assert all("forward" not in layer.__dict__ for layer in dec.layers)
    result = dict(seed=seed, image_ids=list(range(1000)), feature_indices=list(range(14000, 15000)),
                  donor_indices=perm, donor_feature_indices=[14000 + p for p in perm], refs=refs,
                  captions=captions, scores=score_outputs(captions, refs, perm), attention=attn_summary,
                  autogenerated_own_fault_prefix_tokens=prefixes,
                  prefix_definition="re-encode own fault caption: BOS, no EOS, max39, PAD excluded; no reference-conditioned length",
                  prior_anchor_mass={name: float(np.mean(values)) for name, values in prior_mass.items()}, null=null,
                  own_replay_mismatches=dict(fault=0, repair=0),
                  empty_counts={name: sum(not c.strip() for c in cc) for name, cc in captions.items()},
                  state_sha256_before=before, state_sha256_after=after, all_parameters_frozen=True,
                  native_layer_methods_restored=True, native_qk_retained=True, all_logits_and_attentions_finite=True,
                  gates=dec.gate_values(), peak_cuda_allocated_bytes=torch.cuda.max_memory_allocated(),
                  donor_features_sha256=sha256(folder / "donor_features.pt"), gpu_after=gpu_snapshot())
    atomic_json(folder / "results.json", result)


def snapshot_sources():
    originals = {str(p.resolve()): sha256(p) for p in sorted(ORIGINAL.rglob("*")) if p.is_file()}
    inputs = read_json(ORIGINAL / "input_hashes.json")
    for path, expected in inputs.items():
        if sha256(path) != expected:
            raise RuntimeError(f"Original hash-locked input changed: {path}")
    for name, expected in read_json(ORIGINAL / "artifact_hashes.json").items():
        if originals[str((ORIGINAL / name).resolve())] != expected:
            raise RuntimeError(f"Original hash-locked artifact changed: {name}")
    for name in ("run_visual_provenance_control.py", "test_visual_provenance_control.py"):
        path = ROOT / name
        inputs[str(path.resolve())] = sha256(path)
    return dict(original_directory=originals, consumed_inputs=inputs)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--worker", type=int, choices=SEEDS)
    args = ap.parse_args()
    if args.worker is not None:
        run_seed(args.worker)
        return
    OUT.mkdir(exist_ok=False)
    try:
        old_lock = read_json(ORIGINAL / "test_lock.json")
        assert old_lock["chosen_k"] == 16 and not old_lock["test_selection"]
        records = validate_source(read_json(SOURCE))
        perm, attempts = donor_permutation()
        original_donors = [r["mismatch_source"] for r in records]
        assert perm != original_donors, "No reroll: unexpectedly identical to original donor permutation"
        atomic_json(OUT / "local_plan.json", dict(created=time.time(), seeds=list(SEEDS), k=16,
            donor_seed=DONOR_SEED, donor_permutation=perm, donor_generation_attempts=attempts,
            permutation_algorithm="numpy default_rng(20261102).permutation(1000), reject only fixed points",
            original_donor_coincidences=sum(a == b for a, b in zip(perm, original_donors)),
            no_caption_or_outcome_dependent_rerolls=True, source_lock_sha256=sha256(ORIGINAL / "test_lock.json"),
            feature_range=[14000, 15000], donor_mapping="project clean donor features, take p at recipient retained p; recipient mask and plans unchanged",
            reference_access="source validation and scoring only; permutation, features, plans and autogenerated prefixes are caption-reference blind",
            attention_prefix="re-encoded own fault caption BOS+words max39; no EOS appended; exclude PAD; same prefix for own fault/repair",
            null_prefix="same re-encoded own-fault baseline caption as attention probe; identical input to both null plan conditions",
            null_logit_tolerance=1e-4, bootstrap=dict(images=1000, samples=10000, seed=0, seed_average_before_bootstrap=True),
            gpu=dict(physical_id=0, memory_fraction=.35, minimum_free_mib=24000), batch=BATCH,
            post_lock_diagnostic=True, preregistered=False, new_selection=False, training=False, downloads=False))
        hashes = snapshot_sources()
        atomic_json(OUT / "sources.json", hashes)
        for seed in SEEDS:
            uuid, _ = check_gpu0()
            env = dict(os.environ, CUDA_VISIBLE_DEVICES=uuid, PYTHONDONTWRITEBYTECODE="1",
                       HF_HUB_OFFLINE="1", HF_DATASETS_OFFLINE="1", TRANSFORMERS_OFFLINE="1",
                       ATTN_ENCODER="dinov2", CUBLAS_WORKSPACE_CONFIG=":4096:8")
            with (OUT / f"seed{seed}.log").open("x") as stream:
                subprocess.run([sys.executable, "-B", str(Path(__file__).resolve()), "--worker", str(seed)],
                               env=env, stdout=stream, stderr=subprocess.STDOUT, check=True, cwd=ROOT)
        results = [read_json(OUT / f"seed{s}/results.json") for s in SEEDS]
        summary = aggregate(results)
        if snapshot_sources() != hashes:
            raise RuntimeError("Inputs or original control directory changed; not certified complete")
        summary.update(status="complete", all_original_files_and_inputs_unchanged=True,
                       local_plan_sha256=sha256(OUT / "local_plan.json"),
                       per_seed_results={s: sha256(OUT / f"seed{s}/results.json") for s in SEEDS},
                       gpu_final=gpu_snapshot())
        atomic_json(OUT / "results.json", summary)
        atomic_json(OUT / "artifact_hashes.json", {str(p.relative_to(OUT)): sha256(p) for p in sorted(OUT.rglob("*")) if p.is_file()})
        print("Complete:", OUT / "results.json", flush=True)
    except Exception as exc:
        import traceback
        atomic_json(OUT / "failure.json", dict(error=repr(exc), traceback=traceback.format_exc()))
        raise


if __name__ == "__main__":
    main()
